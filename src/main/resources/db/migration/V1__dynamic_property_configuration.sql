-- Dynamic property configuration: amenities, custom fields and their per-property-type mappings.
--
-- Reuses the existing tables: `pgs` (the property), `rooms`, and `lookup_values` (category STAY_TYPE is the
-- property type). Nothing here duplicates them.
--
-- Conventions followed from the existing schema:
--   * the tenant column is `pg_id` (it points at pgs.id), not `property_id`;
--   * tenant-owned tables carry the same audit columns as com.pg.tenant.BaseEntity;
--   * rows are retired with `active = false`, never deleted (room_amenities rows go with their room).
--
-- Portable SQL: runs on PostgreSQL (production) and on H2 in PostgreSQL mode (dev / tests).
-- Idempotent (IF NOT EXISTS), so it is safe on a database where Hibernate (ddl-auto=update) already created
-- the tables from the entities in com.pg.config. The app does not run this file by itself (no migration tool is
-- configured); apply it with psql / your DB tool, or let ddl-auto create the same structure.
--
-- Initial data (categories, amenities, sample mappings for PG / Apartment / Hotel and the extra stay types) is
-- inserted by com.pg.config.ConfigSeeder, only into empty tables, so admin edits are never overwritten.
-- JSON columns are plain VARCHAR holding validated JSON, which keeps them identical on PostgreSQL and H2.

-- ── A. amenity_categories ───────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS amenity_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(255),
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_amenity_categories_code UNIQUE (code)
);

-- ── B. amenities (global master, reusable across property types) ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS amenities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id      BIGINT       NOT NULL,
    code             VARCHAR(40)  NOT NULL,
    name             VARCHAR(100) NOT NULL,
    description      VARCHAR(255),
    icon             VARCHAR(60),
    applicable_level VARCHAR(20)  NOT NULL DEFAULT 'BOTH',
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_amenities_code UNIQUE (code),
    CONSTRAINT fk_amenities_category FOREIGN KEY (category_id) REFERENCES amenity_categories (id),
    CONSTRAINT ck_amenities_level CHECK (applicable_level IN ('PROPERTY', 'ROOM', 'BOTH'))
);
CREATE INDEX IF NOT EXISTS idx_amenities_category ON amenities (category_id);

-- ── C. stay_type_amenities (which amenities a property type offers) ──────────────────────────────────────────
-- stay_type_code holds a lookup_values code of category STAY_TYPE. It is not a database foreign key because
-- lookup_values is unique on (category, code), not on code alone; the API validates it instead.
CREATE TABLE IF NOT EXISTS stay_type_amenities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_type_code   VARCHAR(40) NOT NULL,
    amenity_id       BIGINT      NOT NULL,
    default_selected BOOLEAN     NOT NULL DEFAULT FALSE,
    required         BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order       INTEGER     NOT NULL DEFAULT 0,
    active           BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_stay_type_amenities UNIQUE (stay_type_code, amenity_id),
    CONSTRAINT fk_stay_type_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);
CREATE INDEX IF NOT EXISTS idx_stay_type_amenities_amenity ON stay_type_amenities (amenity_id);

-- ── D. property_field_definitions (custom fields, defined by data) ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS property_field_definitions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40)  NOT NULL,
    label            VARCHAR(120) NOT NULL,
    description      VARCHAR(255),
    field_type       VARCHAR(20)  NOT NULL,
    category         VARCHAR(60),
    placeholder      VARCHAR(160),
    default_value    VARCHAR(500),
    options          VARCHAR(4000),
    validation_rules VARCHAR(2000),
    required         BOOLEAN      NOT NULL DEFAULT FALSE,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_property_field_definitions_code UNIQUE (code),
    CONSTRAINT ck_property_field_definitions_type CHECK (field_type IN
        ('TEXT', 'NUMBER', 'DECIMAL', 'BOOLEAN', 'DATE', 'TIME', 'DROPDOWN', 'MULTI_SELECT', 'CHECKBOX', 'RADIO',
         'IMAGE', 'DOCUMENT'))
);

-- ── E. stay_type_fields (which custom fields a property type asks for) ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS stay_type_fields (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_type_code VARCHAR(40) NOT NULL,
    field_id       BIGINT      NOT NULL,
    required       BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order     INTEGER     NOT NULL DEFAULT 0,
    active         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_stay_type_fields UNIQUE (stay_type_code, field_id),
    CONSTRAINT fk_stay_type_fields_field FOREIGN KEY (field_id) REFERENCES property_field_definitions (id)
);
CREATE INDEX IF NOT EXISTS idx_stay_type_fields_field ON stay_type_fields (field_id);

-- ── F. property_field_values (one row per property and field, typed columns) ─────────────────────────────────
--   TEXT / DROPDOWN / RADIO / DATE (ISO) / TIME (HH:mm) / IMAGE / DOCUMENT (a stored reference) -> value_text
--   NUMBER / DECIMAL                                                                             -> value_number
--   BOOLEAN                                                                                      -> value_boolean
--   MULTI_SELECT / CHECKBOX (JSON array of option values)                                        -> value_json
CREATE TABLE IF NOT EXISTS property_field_values (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pg_id         BIGINT        NOT NULL,
    field_id      BIGINT        NOT NULL,
    value_text    VARCHAR(2000),
    value_number  NUMERIC(19, 4),
    value_boolean BOOLEAN,
    value_json    VARCHAR(2000),
    created_at    TIMESTAMP,
    created_by    VARCHAR(255),
    updated_at    TIMESTAMP,
    updated_by    VARCHAR(255),
    CONSTRAINT uk_property_field_values UNIQUE (pg_id, field_id),
    CONSTRAINT fk_property_field_values_pg FOREIGN KEY (pg_id) REFERENCES pgs (id),
    CONSTRAINT fk_property_field_values_field FOREIGN KEY (field_id) REFERENCES property_field_definitions (id)
);
CREATE INDEX IF NOT EXISTS idx_property_field_values_field ON property_field_values (field_id);

-- ── G. property_amenities (property-level selections) ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS property_amenities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pg_id      BIGINT       NOT NULL,
    amenity_id BIGINT       NOT NULL,
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    notes      VARCHAR(500),
    created_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_at TIMESTAMP,
    updated_by VARCHAR(255),
    CONSTRAINT uk_property_amenities UNIQUE (pg_id, amenity_id),
    CONSTRAINT fk_property_amenities_pg FOREIGN KEY (pg_id) REFERENCES pgs (id),
    CONSTRAINT fk_property_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);
CREATE INDEX IF NOT EXISTS idx_property_amenities_amenity ON property_amenities (amenity_id);

-- ── H. room_amenities (room-level selections, kept apart from the property level) ────────────────────────────
-- pg_id is repeated here (as on every other child table) so tenant filtering never needs a join.
CREATE TABLE IF NOT EXISTS room_amenities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pg_id      BIGINT    NOT NULL,
    room_id    BIGINT    NOT NULL,
    amenity_id BIGINT    NOT NULL,
    enabled    BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_at TIMESTAMP,
    updated_by VARCHAR(255),
    CONSTRAINT uk_room_amenities UNIQUE (room_id, amenity_id),
    CONSTRAINT fk_room_amenities_pg FOREIGN KEY (pg_id) REFERENCES pgs (id),
    CONSTRAINT fk_room_amenities_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT fk_room_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);
CREATE INDEX IF NOT EXISTS idx_room_amenities_amenity ON room_amenities (amenity_id);
CREATE INDEX IF NOT EXISTS idx_room_amenities_pg ON room_amenities (pg_id);
